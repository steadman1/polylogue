from collections.abc import Awaitable, Mapping
from typing import Protocol, runtime_checkable

@runtime_checkable
class DBClient[KeyT, ValueT](Protocol):
    def hget(self, key: KeyT, field: KeyT, /) -> Awaitable[ValueT | None]: ...

    def hset(self, key: KeyT, field: KeyT, value: ValueT, /) -> Awaitable[int]: ...

    def hdel(self, key: KeyT, field: KeyT, /) -> Awaitable[int]: ...

    def hgetall(self, key: KeyT, /) -> Awaitable[Mapping[KeyT, ValueT]]: ...
